func TestResourceObservabilityDashboardSharedChartsAfterConfiguredPanelDeletion(t *testing.T) {
	root := template.RootElementDashboard
	var record *template.Template
	writes := 0
	handlers := map[string]http.Handler{
		"POST /v2/template": http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			writes++
			var write template.CreateUpdateTemplateRequest
			assert.NoError(t, json.NewDecoder(r.Body).Decode(&write))
			record = &template.Template{ID: "mixed-dashboard", Title: write.Title, Spec: write.Spec, Metadata: &template.Metadata{RootElement: &root}}
			w.WriteHeader(http.StatusCreated)
			assert.NoError(t, json.NewEncoder(w).Encode(template.Result{Data: record}))
		}),
		"GET /v2/template/{id}": http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			if !assert.Equal(t, record.ID, r.PathValue("id"), "shared charts must not be fetched") {
				http.Error(w, "source lookup forbidden", http.StatusForbidden)
				return
			}
			assert.Empty(t, r.URL.RawQuery)
			assert.NoError(t, json.NewEncoder(w).Encode(template.Result{Data: record}))
		}),
		"PUT /v2/template/{id}": http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			writes++
			assert.Equal(t, record.ID, r.PathValue("id"))
			var write template.CreateUpdateTemplateRequest
			assert.NoError(t, json.NewDecoder(r.Body).Decode(&write))
			record.Title, record.Spec = write.Title, write.Spec
			assert.NoError(t, json.NewEncoder(w).Encode(template.Result{Data: record}))
		}),
		"DELETE /v2/template/{id}": http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			assert.Equal(t, record.ID, r.PathValue("id"))
			w.WriteHeader(http.StatusNoContent)
		}),
	}
	configuration := `resource "signalfx_observability_dashboard" "test" {
 title = "Mixed"
 container = [
   { text = { markdown = "First" } },
   { template_id = "shared" },
   { text = { markdown = "Second" } },
   { template_id = "shared" },
 ]
}`
	firstDeleted := strings.Replace(configuration, `   { text = { markdown = "First" } },`, "", 1)
	bothDeleted := strings.Replace(firstDeleted, `   { text = { markdown = "Second" } },`, "", 1)
	retitled := strings.Replace(bothDeleted, `title = "Mixed"`, `title = "Retitled"`, 1)
	changedReference := strings.Replace(retitled, `template_id = "shared"`, `template_id = "shared-new"`, 1)
	testresource.UnitTest(t, testresource.TestCase{
		IsUnitTest:               true,
		TerraformVersionChecks:   []tfversion.TerraformVersionCheck{tfversion.SkipBelow(tfversion.Version1_5_0)},
		ProtoV6ProviderFactories: fwtest.NewMockProto6Server(t, handlers, fwtest.WithMockResources(NewResourceObservabilityDashboard)),
		Steps: []testresource.TestStep{
			{Config: configuration},
			{Config: firstDeleted},
			{Config: firstDeleted, PlanOnly: true},
			{Config: bothDeleted},
			{Config: bothDeleted, PlanOnly: true},
			{Config: retitled},
			{Config: retitled, PlanOnly: true},
			{Config: changedReference, PreConfig: func() {
				record.Spec = json.RawMessage(`{"<Dashboard>":[{"<Panel>":[{"<$import.changed>":[]}]},{"<Panel>":[{"<$import.shared>":[]}]}],"$import:changed":"/v2/template/shared-new","$import:shared":"/v2/template/shared"}`)
			}},
		},
	})
	assert.Equal(t, 4, writes, "configured panel deletions and the title change each update the dashboard")
}

func TestResourceObservabilityDashboardMixedInlineAndSharedCharts(t *testing.T) {
	root := template.RootElementDashboard
	var record *template.Template
	creates, updates, deletes := 0, 0, 0
	expectedReference := "shared-one"
	const raw = `{"<Chart>":[{"<o11y:Text>":[],"widget":{},"chart":{"markdown":"Raw notes"}}]}`
	checkWrite := func(w http.ResponseWriter, r *http.Request) {
		var write template.CreateUpdateTemplateRequest
		if !assert.NoError(t, json.NewDecoder(r.Body).Decode(&write)) {
			http.Error(w, "invalid request", http.StatusBadRequest)
			return
		}
		assert.Equal(t, &root, write.Metadata.RootElement, "only the dashboard is managed")
		var document map[string]json.RawMessage
		if !assert.NoError(t, json.Unmarshal(write.Spec, &document)) {
			http.Error(w, "invalid specification", http.StatusBadRequest)
			return
		}
		var panels []map[string][]json.RawMessage
		if !assert.NoError(t, json.Unmarshal(document[dashifyDashboardElement], &panels)) || !assert.Len(t, panels, 3) {
			http.Error(w, "invalid panels", http.StatusBadRequest)
			return
		}
		assert.JSONEq(t, `{"<Chart>":[{"<o11y:TimeSeriesChart>":[],"widget":{},"chart":{},"datasource":{"program":"A"}}]}`, string(panels[0][dashifyPanelElement][0]))
		assert.JSONEq(t, raw, string(panels[2][dashifyPanelElement][0]))
		if expectedReference != "" {
			assert.Equal(t, []string{"/v2/template/" + expectedReference}, write.Metadata.Imports)
			assert.JSONEq(t, `"/v2/template/`+expectedReference+`"`, string(document["$import:widget1"]))
			assert.JSONEq(t, `{"<$import.widget1>":[]}`, string(panels[1][dashifyPanelElement][0]))
		} else {
			assert.Empty(t, write.Metadata.Imports)
			assert.NotContains(t, document, "$import:widget1")
			assert.JSONEq(t, `{"<Chart>":[{"<o11y:SingleValue>":[],"widget":{},"chart":{},"datasource":{"program":"B"}}]}`, string(panels[1][dashifyPanelElement][0]))
		}
		record = &template.Template{ID: "mixed-dashboard", Title: write.Title, Spec: write.Spec, Metadata: &template.Metadata{RootElement: &root, Imports: write.Metadata.Imports}}
		assert.NoError(t, json.NewEncoder(w).Encode(template.Result{Data: record}))
	}
	handlers := map[string]http.Handler{
		"POST /v2/template": http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			creates++
			w.WriteHeader(http.StatusCreated)
			checkWrite(w, r)
		}),
		"GET /v2/template/{id}": http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			if !assert.Equal(t, "mixed-dashboard", r.PathValue("id"), "configured shared references must not fetch source content") {
				http.NotFound(w, r)
				return
			}
			assert.Empty(t, r.URL.RawQuery, "refresh must not request related shared chart records")
			// No source records are included or available through a separate GET.
			assert.NoError(t, json.NewEncoder(w).Encode(template.Result{Data: record}))
		}),
		"PUT /v2/template/{id}": http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			updates++
			assert.Equal(t, "mixed-dashboard", r.PathValue("id"))
			checkWrite(w, r)
		}),
		"DELETE /v2/template/{id}": http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			deletes++
			assert.Equal(t, "mixed-dashboard", r.PathValue("id"), "shared chart records must not be deleted")
			w.WriteHeader(http.StatusNoContent)
		}),
	}
	configuration := `resource "terraform_data" "shared" { input = "shared-one" }
resource "signalfx_observability_dashboard" "test" {
  title = "Mixed charts"
  container = [
    { metrics_time_series = { program = "A" } },
    { template_id = terraform_data.shared.output },
    { inline_content = jsonencode(` + raw + `) },
  ]
}`
	changed := strings.Replace(configuration, `title = "Mixed charts"`, `title = "Changed"`, 1)
	inlined := strings.Replace(changed, `{ template_id = terraform_data.shared.output }`, `{ metrics_single_value = { program = "B" } }`, 1)
	newReference := strings.Replace(changed, `input = "shared-one"`, `input = "shared-two"`, 1)
	testresource.UnitTest(t, testresource.TestCase{
		IsUnitTest:               true,
		TerraformVersionChecks:   []tfversion.TerraformVersionCheck{tfversion.SkipBelow(tfversion.Version1_5_0)},
		ProtoV6ProviderFactories: fwtest.NewMockProto6Server(t, handlers, fwtest.WithMockResources(NewResourceObservabilityDashboard)),
		Steps: []testresource.TestStep{
			{Config: configuration, Check: testresource.TestCheckResourceAttr("signalfx_observability_dashboard.test", "container.1.template_id", "shared-one")},
			{Config: configuration, PlanOnly: true},
			{Config: changed},
			{Config: changed, PlanOnly: true},
			{PreConfig: func() { expectedReference = "" }, Config: inlined},
			{Config: inlined, PlanOnly: true},
			{PreConfig: func() { expectedReference = "shared-two" }, Config: newReference, Check: testresource.TestCheckResourceAttr("signalfx_observability_dashboard.test", "container.1.template_id", "shared-two")},
			{Config: newReference, PlanOnly: true},
		},
	})
	assert.Equal(t, 1, creates)
	assert.Equal(t, 3, updates)
	assert.Equal(t, 1, deletes)
}

