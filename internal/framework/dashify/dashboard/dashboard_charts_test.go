func TestResourceObservabilityDashboardInlineChartsLifecycle(t *testing.T) {
	root := template.RootElementDashboard
	var record *template.Template
	creates, updates, deletes := 0, 0, 0
	checkWrite := func(r *http.Request, program string) *template.CreateUpdateTemplateRequest {
		var write template.CreateUpdateTemplateRequest
		if !assert.NoError(t, json.NewDecoder(r.Body).Decode(&write)) {
			return nil
		}
		assert.Equal(t, &root, write.Metadata.RootElement)
		assert.Empty(t, write.Metadata.Imports)
		assert.Nil(t, write.Metadata.Datasource)
		var document map[string]json.RawMessage
		if !assert.NoError(t, json.Unmarshal(write.Spec, &document)) {
			return nil
		}
		assert.NotContains(t, string(write.Spec), "$import")
		var panels []map[string][]json.RawMessage
		if !assert.NoError(t, json.Unmarshal(document[dashifyDashboardElement], &panels)) {
			return nil
		}
		if !assert.Len(t, panels, len(inlineChartDocuments)) {
			return nil
		}
		for i, expected := range inlineChartDocuments {
			if !assert.Len(t, panels[i][dashifyPanelElement], 1) {
				return nil
			}
			assert.JSONEq(t, strings.ReplaceAll(expected, `"program":"A"`, `"program":"`+program+`"`), string(panels[i][dashifyPanelElement][0]))
		}
		return &write
	}
	handlers := map[string]http.Handler{
		"POST /v2/template": http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			creates++
			write := checkWrite(r, "A")
			if write == nil {
				http.Error(w, "invalid create", http.StatusBadRequest)
				return
			}
			record = &template.Template{ID: "inline-dashboard", Type: write.Type, Title: write.Title, Spec: write.Spec, Metadata: &template.Metadata{RootElement: &root}}
			w.WriteHeader(http.StatusCreated)
			// An ID-only response must still leave the created dashboard tracked.
			assert.NoError(t, json.NewEncoder(w).Encode(template.Result{Data: &template.Template{ID: record.ID}}))
		}),
		"GET /v2/template/{id}": http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			assert.Equal(t, record.ID, r.PathValue("id"), "literal charts need no source record GETs")
			assert.NoError(t, json.NewEncoder(w).Encode(template.Result{Data: record}))
		}),
		"PUT /v2/template/{id}": http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			updates++
			assert.Equal(t, record.ID, r.PathValue("id"))
			write := checkWrite(r, "B")
			if write == nil {
				http.Error(w, "invalid update", http.StatusBadRequest)
				return
			}
			record.Spec = write.Spec
			assert.NoError(t, json.NewEncoder(w).Encode(template.Result{Data: record}))
		}),
		"DELETE /v2/template/{id}": http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			deletes++
			assert.Equal(t, record.ID, r.PathValue("id"))
			w.WriteHeader(http.StatusNoContent)
		}),
	}
	changed := strings.Replace(inlineChartsConfig, `input = "A"`, `input = "B"`, 1)
	testresource.UnitTest(t, testresource.TestCase{
		IsUnitTest:               true,
		TerraformVersionChecks:   []tfversion.TerraformVersionCheck{tfversion.SkipBelow(tfversion.Version1_5_0)},
		ProtoV6ProviderFactories: fwtest.NewMockProto6Server(t, handlers, fwtest.WithMockResources(NewResourceObservabilityDashboard)),
		Steps: []testresource.TestStep{
			{Config: inlineChartsConfig, Check: testresource.ComposeAggregateTestCheckFunc(
				testresource.TestCheckResourceAttr("signalfx_observability_dashboard.test", "container.#", "6"),
				testresource.TestCheckResourceAttr("signalfx_observability_dashboard.test", "container.0.metrics_time_series.time_range", "-60m"),
			)},
			{Config: inlineChartsConfig, PlanOnly: true},
			{ResourceName: "signalfx_observability_dashboard.test", ImportState: true, ImportStateKind: testresource.ImportBlockWithID, GenerateConfig: true},
			{Config: changed, Check: testresource.TestCheckResourceAttr("signalfx_observability_dashboard.test", "id", "inline-dashboard")},
			{Config: changed, PlanOnly: true},
		},
	})
	assert.Equal(t, 1, creates)
	assert.Equal(t, 1, updates)
	assert.Equal(t, 1, deletes)
}

func TestResourceObservabilityDashboardImportsSourceChartsInline(t *testing.T) {
	for _, included := range []bool{false, true} {
		t.Run(fmt.Sprintf("includes=%t", included), func(t *testing.T) {
			root, chartRoot := template.RootElementDashboard, template.RootElementChart
			typed := template.Template{ID: "source-typed", Spec: json.RawMessage(inlineChartDocuments[0]), Metadata: &template.Metadata{RootElement: &chartRoot}}
			const rawChart = `{"<Chart>":[{"<o11y:SingleValue>":[],"widget":{},"datasource":{"program":"A"},"chart":{"future":{"sampleCount":9007199254740993}}}]}`
			raw := template.Template{ID: "source-raw", Spec: json.RawMessage(rawChart), Metadata: &template.Metadata{RootElement: &chartRoot}}
			record := template.Template{ID: "ui-dashboard", Type: fwdashify.ObservabilityTemplateRecordType, Title: "Imported", Metadata: &template.Metadata{RootElement: &root}, Spec: json.RawMessage(`{
  "<Dashboard>":[{"<Panel>":[{"<$import.typed>":[]}]},{"<Panel>":[{"<Chart>":[{"<$import.typed>":[]}]}]},{"<Panel>":[{"<$import.raw>":[]}]}],
  "$import:typed":"/v2/template/source-typed", "$import:raw":"/v2/template/source-raw"
}`)}
			original := string(record.Spec)
			writes, deletes, referenceReads := 0, 0, 0
			sourceReads := map[string]int{}
			handlers := map[string]http.Handler{
				"GET /v2/template/{id}": http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
					var result template.Result
					switch id := r.PathValue("id"); id {
					case record.ID:
						result.Data = &record
						if strings.Contains(string(record.Spec), "$import") {
							referenceReads++
						}
						if included {
							// Exercise the self-only include form as well as ordinary IDs.
							selfOnly := typed
							selfOnly.ID, selfOnly.Self = "", "/v2/template/source-typed"
							result.Includes = []template.Template{selfOnly, raw}
						}
					case typed.ID:
						sourceReads[id]++
						result.Data = &typed
					case raw.ID:
						sourceReads[id]++
						result.Data = &raw
					default:
						t.Errorf("unexpected Template GET %q", id)
						http.NotFound(w, r)
						return
					}
					assert.NoError(t, json.NewEncoder(w).Encode(result))
				}),
				"PUT /v2/template/{id}": http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
					writes++
					assert.Equal(t, record.ID, r.PathValue("id"), "source charts must never be updated")
					var write template.CreateUpdateTemplateRequest
					if !assert.NoError(t, json.NewDecoder(r.Body).Decode(&write)) {
						http.Error(w, "invalid update", http.StatusBadRequest)
						return
					}
					assert.Empty(t, write.Metadata.Imports)
					assert.NotContains(t, string(write.Spec), "$import")
					var spec map[string]json.RawMessage
					if !assert.NoError(t, json.Unmarshal(write.Spec, &spec)) {
						http.Error(w, "invalid spec", http.StatusBadRequest)
						return
					}
					var panels []map[string][]json.RawMessage
					if !assert.NoError(t, json.Unmarshal(spec[dashifyDashboardElement], &panels)) {
						http.Error(w, "invalid panels", http.StatusBadRequest)
						return
					}
					if !assert.Len(t, panels, 3) {
						http.Error(w, "invalid panel count", http.StatusBadRequest)
						return
					}
					assert.JSONEq(t, inlineChartDocuments[0], string(panels[0][dashifyPanelElement][0]))
					assert.JSONEq(t, inlineChartDocuments[0], string(panels[1][dashifyPanelElement][0]))
					assert.JSONEq(t, rawChart, string(panels[2][dashifyPanelElement][0]))
					record.Title, record.Spec = write.Title, write.Spec
					assert.NoError(t, json.NewEncoder(w).Encode(template.Result{Data: &record}))
				}),
				"DELETE /v2/template/{id}": http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
					deletes++
					assert.Equal(t, record.ID, r.PathValue("id"), "destroy must leave source records intact")
					w.WriteHeader(http.StatusNoContent)
				}),
			}
			configuration := `resource "signalfx_observability_dashboard" "test" {
  title = "Imported"
  container = [
    { metrics_time_series = { program = "A", time_range = "-1h", show_legend = false } },
    { metrics_time_series = { program = "A", time_range = "-1h", show_legend = false } },
    { inline_content = jsonencode(` + rawChart + `) },
  ]
}`
			testresource.UnitTest(t, testresource.TestCase{
				IsUnitTest:               true,
				TerraformVersionChecks:   []tfversion.TerraformVersionCheck{tfversion.SkipBelow(tfversion.Version1_5_0)},
				ProtoV6ProviderFactories: fwtest.NewMockProto6Server(t, handlers, fwtest.WithMockResources(NewResourceObservabilityDashboard)),
				Steps: []testresource.TestStep{
					{Config: "import {\n to = signalfx_observability_dashboard.test\n id = \"ui-dashboard\"\n}\n" + configuration},
					{Config: configuration, PlanOnly: true},
					{ResourceName: "signalfx_observability_dashboard.test", ImportState: true, ImportStateKind: testresource.ImportBlockWithID, GenerateConfig: true},
					{PreConfig: func() {
						assert.Zero(t, writes)
						assert.Equal(t, original, string(record.Spec), "import and refresh cannot convert remote storage")
					}, Config: strings.Replace(configuration, `title = "Imported"`, `title = "Changed"`, 1)},
					{Config: strings.Replace(configuration, `title = "Imported"`, `title = "Changed"`, 1), PlanOnly: true},
				},
			})
			assert.Equal(t, 1, writes)
			assert.Equal(t, 1, deletes)
			assert.Equal(t, json.RawMessage(inlineChartDocuments[0]), typed.Spec) //nolint:testifylint // Source records must remain byte-for-byte unchanged.
			assert.Equal(t, json.RawMessage(rawChart), raw.Spec)                  //nolint:testifylint // Source records must remain byte-for-byte unchanged.
			if included {
				assert.Empty(t, sourceReads)
			} else {
				assert.Equal(t, referenceReads, sourceReads[typed.ID], "a repeated chart is fetched once per read")
				assert.Equal(t, referenceReads, sourceReads[raw.ID])
			}
		})
	}
}

func TestResourceObservabilityDashboardInlineChartValidation(t *testing.T) {
	for _, test := range []struct{ name, input, content, want string }{
		{"two chart types", `"A"`, `{ text = {}, metrics_time_series = { program = "A" } }`, "Invalid panel content"},
		{"typed and raw", `"A"`, `{ text = {}, inline_content = "{\"<Chart>\":[]}" }`, "Invalid panel content"},
		{"typed and shared", `"A"`, `{ text = {}, template_id = "shared" }`, "Invalid panel content"},
		{"raw and shared", `"A"`, `{ inline_content = "{\"<Chart>\":[]}", template_id = "shared" }`, "Invalid panel content"},
		{"empty reference", `"A"`, `{ template_id = "" }`, "must be non-empty"},
		{"reference API path", `"A"`, `{ template_id = "/v2/template/shared" }`, "without an API path"},
		{"known invalid with unknown program", `"A"`, `{ metrics_time_series = { program = terraform_data.value.output, visualization = "pie" } }`, "must be one of"},
		{"invalid with unknown layout", `{ width = "1/2" }`, `{ metrics_time_series = { program = "" }, layout = terraform_data.value.output }`, "must contain at least 1 characters"},
		{"null panel", `"A"`, `null`, "non-null panel"},
		{"whole chart", `{ program = "A" }`, `{ metrics_time_series = terraform_data.value.output }`, ""},
		{"whole panel", `{ metrics_time_series = { program = "A" } }`, `terraform_data.value.output`, ""},
		{"computed reference", `"shared"`, `{ template_id = terraform_data.value.output }`, ""},
		{"conditional chart types", `true`, `{ text = terraform_data.value.output ? { markdown = "Notes" } : null, metrics_time_series = terraform_data.value.output ? null : { program = "A" } }`, ""},
		{"known invalid chart with unknown alternative", `{}`, `{ text = terraform_data.value.output, metrics_time_series = { program = "" } }`, "must contain at least 1 characters"},
		{"known conflicts with unknown alternative", `{}`, `{ metrics_list = terraform_data.value.output, text = {}, metrics_time_series = { program = "A" } }`, "Invalid panel content"},
	} {
		t.Run(test.name, func(t *testing.T) {
			step := testresource.TestStep{Config: `resource "terraform_data" "value" { input = ` + test.input + ` }
resource "signalfx_observability_dashboard" "test" {
 title = "Inline validation"
 container = [` + test.content + `]
}`, PlanOnly: true}
			if test.want != "" {
				step.ExpectError = regexp.MustCompile(test.want)
			} else {
				step.ExpectNonEmptyPlan = true
			}
			testresource.UnitTest(t, testresource.TestCase{
				IsUnitTest:               true,
				TerraformVersionChecks:   []tfversion.TerraformVersionCheck{tfversion.SkipBelow(tfversion.Version1_5_0)},
				ProtoV6ProviderFactories: fwtest.NewMockProto6Server(t, nil, fwtest.WithMockResources(NewResourceObservabilityDashboard)),
				Steps:                    []testresource.TestStep{step},
			})
		})
	}
}

